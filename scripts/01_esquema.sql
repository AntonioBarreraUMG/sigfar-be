-- DBeaver / Oracle XE | 01: Esquema (ALT+X en un esquema NUEVO).
-- SIGFAR | 01_esquema.sql
-- Ejecutar en DBeaver conectado a una PDB de Oracle XE con el usuario SIGFAR.
-- Ejecutar conectado al ESQUEMA de SIGFAR dentro de una PDB.
-- PRECAUCION: pensado para una instalacion nueva; NO elimina tablas existentes.


-- 01. Acceso
CREATE TABLE rol (
    id_rol          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_rol PRIMARY KEY,
    nombre          VARCHAR2(30 CHAR) NOT NULL,
    CONSTRAINT uk_rol_nombre UNIQUE (nombre)
);

-- 02. Sucursales
CREATE TABLE sucursal (
    id_sucursal         NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_sucursal PRIMARY KEY,
    codigo              VARCHAR2(20 CHAR) NOT NULL,
    nombre              VARCHAR2(120 CHAR) NOT NULL,
    tipo                VARCHAR2(25 CHAR) NOT NULL,
    departamento        VARCHAR2(80 CHAR) NOT NULL,
    municipio           VARCHAR2(80 CHAR) NOT NULL,
    direccion           VARCHAR2(250 CHAR) NOT NULL,
    tiempo_entrega_min  NUMBER(5) NOT NULL,
    activa              CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT uk_sucursal_codigo UNIQUE (codigo),
    CONSTRAINT ck_sucursal_tipo CHECK (tipo IN ('CENTRO_COMERCIAL', 'GASOLINERA')),
    CONSTRAINT ck_sucursal_tiempo CHECK (tiempo_entrega_min > 0),
    CONSTRAINT ck_sucursal_activa CHECK (activa IN ('S', 'N'))
);

-- 03. Usuarios: la administracion de cuentas se limita a la demostracion.
CREATE TABLE usuario (
    id_usuario      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_usuario PRIMARY KEY,
    id_rol          NUMBER(10) NOT NULL,
    id_sucursal     NUMBER(10),
    nombre          VARCHAR2(120 CHAR) NOT NULL,
    correo          VARCHAR2(150 CHAR) NOT NULL,
    clave_hash      VARCHAR2(255 CHAR) NOT NULL,
    activo          CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT uk_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_activo CHECK (activo IN ('S', 'N')),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol),
    CONSTRAINT fk_usuario_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id_sucursal)
);

-- 04. Catalogo basico
CREATE TABLE medicamento (
    id_medicamento  NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_medicamento PRIMARY KEY,
    codigo          VARCHAR2(30 CHAR) NOT NULL,
    nombre          VARCHAR2(150 CHAR) NOT NULL,
    presentacion    VARCHAR2(100 CHAR) NOT NULL,
    activo          CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT uk_medicamento_codigo UNIQUE (codigo),
    CONSTRAINT ck_medicamento_activo CHECK (activo IN ('S', 'N'))
);

-- 05. Saldo por sucursal y medicamento
CREATE TABLE inventario_sucursal (
    id_sucursal       NUMBER(10) NOT NULL,
    id_medicamento    NUMBER(10) NOT NULL,
    cantidad_existente NUMBER(10) DEFAULT 0 NOT NULL,
    cantidad_reservada NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_inventario_sucursal PRIMARY KEY (id_sucursal, id_medicamento),
    CONSTRAINT ck_inv_existencia CHECK (cantidad_existente >= 0),
    CONSTRAINT ck_inv_reserva CHECK (cantidad_reservada >= 0 AND cantidad_reservada <= cantidad_existente),
    CONSTRAINT fk_inv_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id_sucursal),
    CONSTRAINT fk_inv_medicamento FOREIGN KEY (id_medicamento) REFERENCES medicamento (id_medicamento)
);

-- 06. Transferencias: el despacho y la recepcion son transacciones separadas
CREATE TABLE transferencia (
    id_transferencia    NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_transferencia PRIMARY KEY,
    id_sucursal_origen  NUMBER(10) NOT NULL,
    id_sucursal_destino NUMBER(10) NOT NULL,
    id_usuario_registro NUMBER(10) NOT NULL,
    id_usuario_despacho NUMBER(10),
    id_usuario_recepcion NUMBER(10),
    estado              VARCHAR2(20 CHAR) DEFAULT 'REGISTRADA' NOT NULL,
    fecha_registro      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_despacho      TIMESTAMP WITH TIME ZONE,
    fecha_recepcion     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_transferencia_sucursales CHECK (id_sucursal_origen <> id_sucursal_destino),
    CONSTRAINT ck_transferencia_estado CHECK (estado IN ('REGISTRADA', 'EN_TRANSITO', 'RECIBIDA')),
    CONSTRAINT ck_transferencia_fechas CHECK (
        (fecha_despacho IS NULL OR fecha_despacho >= fecha_registro) AND
        (fecha_recepcion IS NULL OR fecha_recepcion >= fecha_despacho)
    ),
    CONSTRAINT ck_transferencia_transicion CHECK (
        (estado = 'REGISTRADA' AND fecha_despacho IS NULL AND fecha_recepcion IS NULL AND
         id_usuario_despacho IS NULL AND id_usuario_recepcion IS NULL)
        OR
        (estado = 'EN_TRANSITO' AND fecha_despacho IS NOT NULL AND fecha_recepcion IS NULL AND
         id_usuario_despacho IS NOT NULL AND id_usuario_recepcion IS NULL)
        OR
        (estado = 'RECIBIDA' AND fecha_despacho IS NOT NULL AND fecha_recepcion IS NOT NULL AND
         id_usuario_despacho IS NOT NULL AND id_usuario_recepcion IS NOT NULL)
    ),
    CONSTRAINT fk_tra_origen FOREIGN KEY (id_sucursal_origen) REFERENCES sucursal (id_sucursal),
    CONSTRAINT fk_tra_destino FOREIGN KEY (id_sucursal_destino) REFERENCES sucursal (id_sucursal),
    CONSTRAINT fk_tra_usu_reg FOREIGN KEY (id_usuario_registro) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_tra_usu_des FOREIGN KEY (id_usuario_despacho) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_tra_usu_rec FOREIGN KEY (id_usuario_recepcion) REFERENCES usuario (id_usuario)
);

-- 07. Renglones de transferencia
CREATE TABLE detalle_transferencia (
    id_detalle_transferencia NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_detalle_transferencia PRIMARY KEY,
    id_transferencia    NUMBER(10) NOT NULL,
    id_medicamento     NUMBER(10) NOT NULL,
    cantidad           NUMBER(10) NOT NULL,
    CONSTRAINT uk_det_tra_medicamento UNIQUE (id_transferencia, id_medicamento),
    CONSTRAINT ck_det_tra_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_det_tra_transferencia FOREIGN KEY (id_transferencia) REFERENCES transferencia (id_transferencia),
    CONSTRAINT fk_det_tra_medicamento FOREIGN KEY (id_medicamento) REFERENCES medicamento (id_medicamento)
);

-- 08. Solicitud interna de entrega (NO es un portal publico de compras)
CREATE TABLE solicitud_entrega (
    id_solicitud          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_solicitud_entrega PRIMARY KEY,
    id_usuario_registro   NUMBER(10) NOT NULL,
    id_sucursal_asignada  NUMBER(10),
    cliente_nombre        VARCHAR2(120 CHAR) NOT NULL,
    cliente_telefono      VARCHAR2(20 CHAR) NOT NULL,
    departamento_entrega  VARCHAR2(80 CHAR) NOT NULL,
    municipio_entrega     VARCHAR2(80 CHAR) NOT NULL,
    direccion_entrega     VARCHAR2(250 CHAR) NOT NULL,
    forma_pago            VARCHAR2(15 CHAR),
    estado                VARCHAR2(20 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    fecha_solicitud       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_confirmacion    TIMESTAMP WITH TIME ZONE,
    fecha_despacho        TIMESTAMP WITH TIME ZONE,
    fecha_estimada_entrega TIMESTAMP WITH TIME ZONE,
    fecha_entrega_real    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_sol_estado CHECK (estado IN ('PENDIENTE','CONFIRMADA','DESPACHADA','ENTREGADA','CANCELADA')),
    CONSTRAINT ck_sol_pago CHECK (forma_pago IS NULL OR forma_pago IN ('EFECTIVO','TARJETA')),
    CONSTRAINT ck_sol_estado_fechas CHECK (
        (estado <> 'PENDIENTE' OR
           (id_sucursal_asignada IS NULL AND fecha_confirmacion IS NULL AND fecha_despacho IS NULL AND
            fecha_estimada_entrega IS NULL AND fecha_entrega_real IS NULL AND forma_pago IS NULL))
        AND
        (estado NOT IN ('CONFIRMADA','DESPACHADA','ENTREGADA') OR
           (id_sucursal_asignada IS NOT NULL AND forma_pago IS NOT NULL AND
            fecha_confirmacion IS NOT NULL AND fecha_estimada_entrega IS NOT NULL))
        AND
        (estado <> 'CONFIRMADA' OR (fecha_despacho IS NULL AND fecha_entrega_real IS NULL))
        AND
        (estado NOT IN ('DESPACHADA','ENTREGADA') OR fecha_despacho IS NOT NULL)
        AND
        (estado <> 'DESPACHADA' OR fecha_entrega_real IS NULL)
        AND
        (estado <> 'ENTREGADA' OR fecha_entrega_real IS NOT NULL)
        AND
        (estado <> 'CANCELADA' OR (fecha_despacho IS NULL AND fecha_entrega_real IS NULL))
    ),
    CONSTRAINT ck_sol_orden_fechas CHECK (
        (fecha_confirmacion IS NULL OR fecha_confirmacion >= fecha_solicitud) AND
        (fecha_estimada_entrega IS NULL OR fecha_estimada_entrega > fecha_confirmacion) AND
        (fecha_despacho IS NULL OR fecha_despacho >= fecha_confirmacion) AND
        (fecha_entrega_real IS NULL OR fecha_entrega_real >= fecha_despacho)
    ),
    CONSTRAINT fk_sol_usuario FOREIGN KEY (id_usuario_registro) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_sol_sucursal FOREIGN KEY (id_sucursal_asignada) REFERENCES sucursal (id_sucursal)
);

-- 09. Detalle de medicamentos solicitados
CREATE TABLE detalle_solicitud (
    id_detalle_solicitud NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_detalle_solicitud PRIMARY KEY,
    id_solicitud      NUMBER(10) NOT NULL,
    id_medicamento   NUMBER(10) NOT NULL,
    cantidad         NUMBER(10) NOT NULL,
    CONSTRAINT uk_det_sol_medicamento UNIQUE (id_solicitud, id_medicamento),
    CONSTRAINT ck_det_sol_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_det_sol_solicitud FOREIGN KEY (id_solicitud) REFERENCES solicitud_entrega (id_solicitud),
    CONSTRAINT fk_det_sol_medicamento FOREIGN KEY (id_medicamento) REFERENCES medicamento (id_medicamento)
);

-- 10. Historial de entradas y salidas de medicamento
CREATE TABLE movimiento_inventario (
    id_movimiento            NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_movimiento_inventario PRIMARY KEY,
    id_sucursal              NUMBER(10) NOT NULL,
    id_medicamento           NUMBER(10) NOT NULL,
    id_usuario               NUMBER(10) NOT NULL,
    id_detalle_transferencia NUMBER(10),
    id_detalle_solicitud     NUMBER(10),
    tipo                     VARCHAR2(30 CHAR) NOT NULL,
    cantidad                 NUMBER(10) NOT NULL,
    motivo                   VARCHAR2(250 CHAR),
    fecha_movimiento         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_mov_inv_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_mov_inv_tipo CHECK (tipo IN (
      'INICIAL', 'AJUSTE_ENTRADA', 'AJUSTE_SALIDA',
      'TRANSFERENCIA_SALIDA', 'TRANSFERENCIA_ENTRADA', 'ENTREGA_SALIDA'
    )),
    CONSTRAINT ck_mov_inv_ajuste CHECK (
      tipo NOT IN ('AJUSTE_ENTRADA', 'AJUSTE_SALIDA') OR TRIM(motivo) IS NOT NULL
    ),
    CONSTRAINT ck_mov_inv_referencia CHECK (
      (tipo IN ('INICIAL','AJUSTE_ENTRADA','AJUSTE_SALIDA') AND id_detalle_transferencia IS NULL AND id_detalle_solicitud IS NULL)
      OR
      (tipo IN ('TRANSFERENCIA_SALIDA','TRANSFERENCIA_ENTRADA') AND id_detalle_transferencia IS NOT NULL AND id_detalle_solicitud IS NULL)
      OR
      (tipo = 'ENTREGA_SALIDA' AND id_detalle_transferencia IS NULL AND id_detalle_solicitud IS NOT NULL)
    ),
    CONSTRAINT fk_mov_inv_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id_sucursal),
    CONSTRAINT fk_mov_inv_medicamento FOREIGN KEY (id_medicamento) REFERENCES medicamento (id_medicamento),
    CONSTRAINT fk_mov_inv_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_mov_inv_det_tra FOREIGN KEY (id_detalle_transferencia) REFERENCES detalle_transferencia (id_detalle_transferencia),
    CONSTRAINT fk_mov_inv_det_sol FOREIGN KEY (id_detalle_solicitud) REFERENCES detalle_solicitud (id_detalle_solicitud)
);

-- 11. Movimientos de efectivo; no equivale a contabilidad ni saldo bancario
CREATE TABLE movimiento_efectivo (
    id_movimiento_efectivo NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_movimiento_efectivo PRIMARY KEY,
    id_sucursal           NUMBER(10) NOT NULL,
    id_usuario            NUMBER(10) NOT NULL,
    tipo                  VARCHAR2(10 CHAR) NOT NULL,
    concepto              VARCHAR2(250 CHAR) NOT NULL,
    monto                 NUMBER(14,2) NOT NULL,
    fecha_movimiento      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_mov_efe_tipo CHECK (tipo IN ('INGRESO','EGRESO')),
    CONSTRAINT ck_mov_efe_monto CHECK (monto > 0),
    CONSTRAINT fk_mov_efe_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id_sucursal),
    CONSTRAINT fk_mov_efe_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

-- 12. Gasto agregado por sucursal y periodo (no se calcula nomina individual)
CREATE TABLE gasto_planilla (
    id_gasto_planilla NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_gasto_planilla PRIMARY KEY,
    id_sucursal       NUMBER(10) NOT NULL,
    id_usuario        NUMBER(10) NOT NULL,
    periodo           CHAR(7) NOT NULL,
    monto_total       NUMBER(14,2) NOT NULL,
    fecha_registro    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uk_gasto_planilla_periodo UNIQUE (id_sucursal, periodo),
    CONSTRAINT ck_gasto_planilla_periodo CHECK (REGEXP_LIKE(periodo, '^[0-9]{4}-(0[1-9]|1[0-2])$')),
    CONSTRAINT ck_gasto_planilla_monto CHECK (monto_total >= 0),
    CONSTRAINT fk_gasto_planilla_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id_sucursal),
    CONSTRAINT fk_gasto_planilla_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

-- 13. Valor declarado de activos; sin depreciacion
CREATE TABLE activo_fijo (
    id_activo            NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_activo_fijo PRIMARY KEY,
    id_sucursal          NUMBER(10) NOT NULL,
    id_usuario_registro  NUMBER(10) NOT NULL,
    codigo               VARCHAR2(30 CHAR) NOT NULL,
    descripcion          VARCHAR2(200 CHAR) NOT NULL,
    valor                NUMBER(14,2) NOT NULL,
    estado               VARCHAR2(15 CHAR) DEFAULT 'VIGENTE' NOT NULL,
    fecha_registro       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uk_activo_codigo UNIQUE (codigo),
    CONSTRAINT ck_activo_valor CHECK (valor >= 0),
    CONSTRAINT ck_activo_estado CHECK (estado IN ('VIGENTE','BAJA')),
    CONSTRAINT fk_activo_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id_sucursal),
    CONSTRAINT fk_activo_usuario FOREIGN KEY (id_usuario_registro) REFERENCES usuario (id_usuario)
);

-- 14. Cada detalle de solicitud puede tener una reserva
CREATE TABLE reserva_inventario (
    id_reserva           NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_reserva_inventario PRIMARY KEY,
    id_detalle_solicitud NUMBER(10) NOT NULL,
    id_sucursal          NUMBER(10) NOT NULL,
    cantidad             NUMBER(10) NOT NULL,
    estado               VARCHAR2(15 CHAR) DEFAULT 'ACTIVA' NOT NULL,
    fecha_reserva        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uk_reserva_detalle UNIQUE (id_detalle_solicitud),
    CONSTRAINT ck_reserva_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('ACTIVA','CONSUMIDA','LIBERADA')),
    CONSTRAINT fk_reserva_detalle FOREIGN KEY (id_detalle_solicitud) REFERENCES detalle_solicitud (id_detalle_solicitud),
    CONSTRAINT fk_reserva_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id_sucursal)
);

-- 15. Bitacora central: datos JSON textuales opcionales (nunca credenciales)
CREATE TABLE registro_auditoria (
    id_auditoria       NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_registro_auditoria PRIMARY KEY,
    id_usuario        NUMBER(10) NOT NULL,
    id_sucursal       NUMBER(10),
    entidad           VARCHAR2(60 CHAR) NOT NULL,
    id_registro       NUMBER(10) NOT NULL,
    accion            VARCHAR2(40 CHAR) NOT NULL,
    datos_anteriores  CLOB,
    datos_nuevos      CLOB,
    fecha_evento      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_audit_sucursal FOREIGN KEY (id_sucursal) REFERENCES sucursal (id_sucursal)
);

CREATE INDEX ix_mov_inv_sucursal_fecha ON movimiento_inventario (id_sucursal, fecha_movimiento);
CREATE INDEX ix_mov_inv_medicamento ON movimiento_inventario (id_medicamento);
CREATE INDEX ix_tra_origen_estado ON transferencia (id_sucursal_origen, estado);
CREATE INDEX ix_tra_destino_estado ON transferencia (id_sucursal_destino, estado);
CREATE INDEX ix_mov_efe_sucursal_fecha ON movimiento_efectivo (id_sucursal, fecha_movimiento);
CREATE INDEX ix_sol_estado_fecha ON solicitud_entrega (estado, fecha_solicitud);
CREATE INDEX ix_suc_ubicacion ON sucursal (departamento, municipio);
CREATE INDEX ix_audit_sucursal_fecha ON registro_auditoria (id_sucursal, fecha_evento);
CREATE INDEX ix_audit_entidad_registro ON registro_auditoria (entidad, id_registro);
CREATE INDEX ix_det_tra_med ON detalle_transferencia (id_medicamento);
CREATE INDEX ix_det_sol_med ON detalle_solicitud (id_medicamento);

